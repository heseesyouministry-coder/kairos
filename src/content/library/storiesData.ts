export function getStoriesForBook(bookId: string): LibraryStoryView[] {
  return ALL_LIBRARY_STORIES.filter((s) => s.bookId.toLowerCase() === bookId.toLowerCase());
}

export function getStory(bookId: string, storyId: string): LibraryStoryView | undefined {
  return ALL_LIBRARY_STORIES.find(
    (s) => s.bookId.toLowerCase() === bookId.toLowerCase() && s.storyId.toLowerCase() === storyId.toLowerCase()
  );
}

export function getLibraryStoryForScene(sceneId: string): LibraryStoryView | undefined {
  return ALL_LIBRARY_STORIES.find(
    (s) => s.sceneId === sceneId || (s.subSceneIds && s.subSceneIds.includes(sceneId))
  );
}
