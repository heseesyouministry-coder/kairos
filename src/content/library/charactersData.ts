export function getCharacterById(id: string): BiblicalCharacter | undefined {
  return ALL_CHARACTERS.find((c) => c.id.toLowerCase() === id.toLowerCase());
}

export function getCharactersForStory(characterIds: string[]): BiblicalCharacter[] {
  return ALL_CHARACTERS.filter((c) => characterIds.includes(c.id));
}

export function getCharactersForBook(storyIds: string[]): BiblicalCharacter[] {
  return ALL_CHARACTERS.filter((c) => c.stories.some((s) => storyIds.includes(s)));
}
